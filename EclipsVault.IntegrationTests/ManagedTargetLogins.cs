using System.Security.Cryptography;
using Microsoft.Data.SqlClient;

namespace EclipsVault.IntegrationTests;

/// <summary>Real logins on a vault's managed target, created and checked as its administrator would.</summary>
internal static class ManagedTargetLogins
{
    /// <summary>Letters and digits only: the vault refuses to render anything else into its rotation statement.</summary>
    public static string NewPassword() => "It1" + Convert.ToHexString(RandomNumberGenerator.GetBytes(16));

    public static async Task CreateAsync(VaultFixture vault, string login, string password)
    {
        await using var connection = new SqlConnection(vault.ManagedTargetConnectionString);
        await connection.OpenAsync();
        await using var command = connection.CreateCommand();
        // Both values are generated by the test, letters, digits and underscores only.
        command.CommandText = $"CREATE LOGIN [{login}] WITH PASSWORD = '{password}'";
        await command.ExecuteNonQueryAsync();
    }

    /// <summary>Whether the target accepts <paramref name="password"/> for <paramref name="login"/> right now.</summary>
    public static async Task<bool> OpensWithAsync(VaultFixture vault, string login, string password)
    {
        var asLogin = new SqlConnectionStringBuilder(vault.ManagedTargetConnectionString)
        {
            UserID = login,
            Password = password,
            // A refused password must not be served from a pool opened with the one before it.
            Pooling = false,
        };
        await using var connection = new SqlConnection(asLogin.ConnectionString);
        try
        {
            await connection.OpenAsync();
            return true;
        }
        catch (SqlException)
        {
            return false;
        }
    }
}
